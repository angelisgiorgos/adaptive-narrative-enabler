class ArtifactImportTests(_Records):
    """Files in an artifacts folder become recorded engines and games (python main.py --import-artifacts)."""

    def test_engines_and_games_are_recorded_completed_linked_and_moved(self):
        from core_engine import Genome

        folder = self.dir / "artifacts"
        folder.mkdir()
        evolution, result = _train(1)
        model = EngineModel.from_training(evolution, result, source="test run")
        model.save(folder / "engine.zip")                                    # an engine model
        same = dict(model.config, generated_run={"genome": model.genome_traits, "best_score": 1.0})
        (folder / "same.yaml").write_text(yaml.safe_dump(same))             # its story configuration: linked
        older = {k: v for k, v in model.config.items() if k not in ("director", "mission_selection")}
        other = Genome(random.Random(77)).traits()
        with zipfile.ZipFile(folder / "bundle.zip", "w") as archive:        # an older bundle, other storyteller
            archive.writestr("config.yaml", yaml.safe_dump(older))
            archive.writestr("best_model.yaml", yaml.safe_dump({"best_score": 12.5, "genome": str(other)}))
        (folder / "notes.yaml").write_text("just: notes\n")                 # not an engine: stays

        report = sessions.import_artifacts(folder)
        self.assertEqual((report["engines"], report["linked"], report["previews"]), (2, 1, 2))
        self.assertEqual([f["file"] for f in report["failed"]], ["notes.yaml"])
        self.assertEqual(sorted(p.name for p in folder.iterdir()), ["notes.yaml"])   # the others were moved
        engines = {e["id"]: e for e in records.list_engines() if e["source"] != "generation_champion"}
        self.assertIn(model.id, engines)                                    # the model keeps its id
        imported = next(e for e in engines.values() if e["id"] != model.id)
        self.assertEqual((imported["origin"], imported["score"]), ("import", 12.5))
        loaded = records.load_engine(imported["id"])                         # completed and playable
        self.assertEqual(loaded.genome_traits, {k: float(v) for k, v in other.items()})
        self.assertIn("director", loaded.config)
        self.assertTrue(loaded.tag_vectors)
        kinds = {row[0] for row in self._db("SELECT kind FROM artifacts WHERE engine_id IS NOT NULL")}
        self.assertTrue({"imported_engine_model", "imported_story_config", "imported_engine_bundle"} <= kinds)
        self.assertEqual(len(self._db("SELECT 1 FROM stories WHERE kind = 'preview' AND origin = 'import'")), 2)
        self.assertEqual(self._db("SELECT run_id IS NOT NULL FROM engines WHERE id = ?", model.id), [(1,)])

        again = sessions.import_artifacts(folder)                            # nothing left to import twice
        self.assertEqual((again["engines"], again["linked"]), (0, 0))


