def _train(generations, seed=4):
    evolution = NarrativeEvolution(engine.build_world, fitness, settings={**QUICK, "generations": generations},
                                   seed=seed, memory=ModelMemory())
    return evolution, evolution.run()


class _Folder(unittest.TestCase):
    def setUp(self):
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        self.dir = Path(directory.name)
        self.addCleanup(config.clear_override)  # models activate their own configuration


class EngineModelTests(_Folder):
    @classmethod
    def setUpClass(cls):
        cls.evolution, cls.result = _train(2)
        cls.model = EngineModel.from_training(cls.evolution, cls.result, source="test")

    def test_everything_is_saved_and_checked(self):
        path = self.model.save(self.dir / "engine.ane.zip")
        loaded = EngineModel.load(path)
        self.assertEqual((loaded.id, loaded.source, loaded.score), (self.model.id, "test", self.result.best_score))
        self.assertEqual(loaded.genome_traits, self.result.best_genome.traits())
        self.assertEqual(loaded.config, self.model.config)
        self.assertEqual(loaded.checkpoint, json.loads(json.dumps(self.evolution.last_checkpoint)))
        self.assertEqual(loaded.checkpoint["next_generation"], 2)
        self.assertEqual(len(loaded.checkpoint["population"]), 3)  # the whole population, not just the best
        self.assertTrue(loaded.memory and loaded.tag_vectors and loaded.code_matches())
        manifest = json.loads(zipfile.ZipFile(path).read("manifest.json"))
        self.assertTrue(manifest["resumable"])
        self.assertEqual(set(manifest["files"]), {"config.yaml", "genome.json", "memory.json", "tag_vectors.json",
                                                  "best_model.yaml", "README.txt", "training.json"})

    def test_damage_is_detected(self):
        path = self.model.save(self.dir / "engine.ane.zip")
        damaged = self.dir / "damaged.ane.zip"
        with zipfile.ZipFile(path) as source, zipfile.ZipFile(damaged, "w") as target:
            for item in source.infolist():
                data = source.read(item.filename)
                if item.filename == "genome.json":
                    data = data.replace(b'"score"', b'"score_"')
                target.writestr(item, data)
        with self.assertRaisesRegex(ValueError, "checksum"):
            EngineModel.load(damaged)
        with self.assertRaises(ValueError):
            EngineModel.load(self.dir / "missing.zip")

    def test_older_loaders_read_it_as_a_bundle(self):
        path = self.model.save(self.dir / "engine.zip")
        config_data, genome = sessions._read_engine_artifact(path)
        self.assertEqual(genome.traits(), self.model.genome_traits)
        self.assertIn("world_definition", config_data)

    def test_training_continues_exactly(self):
        _, uninterrupted = _train(4)
        loaded = EngineModel.load(self.model.save(self.dir / "engine.ane.zip"))
        continued, newer = loaded.continue_training(generations=2)
        self.assertEqual([vars(h) for h in continued.history], [vars(h) for h in uninterrupted.history])
        self.assertEqual(continued.best_genome.traits(), uninterrupted.best_genome.traits())
        self.assertEqual((newer.parent_id, newer.checkpoint["next_generation"]), (loaded.id, 4))

    def test_training_continues_exactly_in_another_process(self):
        path = self.model.save(self.dir / "engine.ane.zip")
        code = (f"import sys, json; sys.path.insert(0, {str(ROOT)!r})\n"
                "from core_engine.model import EngineModel\n"
                f"result, newer = EngineModel.load({str(path)!r}).continue_training(generations=2)\n"
                "print(json.dumps([h.validation for h in result.history]))\n")
        out = subprocess.run([PYTHON, "-c", code], cwd=ROOT, capture_output=True, text=True, timeout=600,
                             env={**os.environ, "ANE_RECORDS": "off"})
        self.assertEqual(out.returncode, 0, out.stderr[-2000:])
        _, uninterrupted = _train(4)
        self.assertEqual(json.loads(out.stdout.strip().splitlines()[-1]), [h.validation for h in uninterrupted.history])

    def test_the_world_is_regenerated_and_played(self):
        loaded = EngineModel.load(self.model.save(self.dir / "engine.ane.zip"))
        changed = config.default_config()
        changed["world_definition"]["locations"].pop("Tavern")
        config.use_override(changed)                                  # another world is active now...
        world = loaded.build_world()                                   # ...the model brings back its own
        self.assertEqual(set(world.locations), set(loaded.config["world_definition"]["locations"]))
        self.assertIn("Tavern", world.locations)
        self.assertEqual(yaml.safe_load(loaded.world_yaml()), loaded.config)
        state = loaded.new_game(seed=3)
        for _ in range(5):
            state.step()
        self.assertEqual(len(state.turn_log), state.actions_taken)
        self.assertEqual(state.genome.traits(), loaded.genome_traits)

    def test_retraining_starts_from_the_storyteller(self):
        result, retrained = self.model.retrain({**QUICK, "generations": 1}, seed=9)
        self.assertGreaterEqual(result.warm_started, 1)
        self.assertEqual(retrained.parent_id, self.model.id)
        self.assertEqual(retrained.checkpoint["next_generation"], 1)


class _Records(_Folder):
    def setUp(self):
        super().setUp()
        patcher = patch.dict(os.environ, {"ANE_RECORDS_DIR": str(self.dir / "records"), "ANE_SAVE_DIR": str(self.dir / "saves")})
        patcher.start()
        self.addCleanup(patcher.stop)

    def _db(self, query, *args):
        with sqlite3.connect(records.database_path()) as connection:
            return connection.execute(query, args).fetchall()


class ApiRecordingTests(_Records):
    def setUp(self):
        super().setUp()
        self.client = TestClient(api.api)

    def _simulate(self):
        response = self.client.post("/v1/simulations", json={"candidate_count": 2, "generations": 2,
                                                              "simulation_steps": 6, "deterministic": True})
        self.assertEqual(response.status_code, 200, response.text)
        return response.json()

    def test_a_run_is_recorded_with_everything(self):
        game = self._simulate()
        run = self.client.get(f"/v1/records/runs/{game['run_id']}").json()
        self.assertEqual((run["origin"], run["status"], run["kind"]), ("api", "finished", "evolution"))
        self.assertEqual(run["parameters"]["candidate_count"], 2)
        self.assertEqual(run["settings"]["pop_size"], 2)                      # every resolved setting
        self.assertEqual([g["generation"] for g in run["generations"]], [0, 1])
        sources = sorted(e["source"] for e in run["engines"])
        self.assertEqual(sources, ["generation_champion", "generation_champion", "run_best"])
        best = next(e for e in run["engines"] if e["source"] == "run_best")
        self.assertEqual(best["id"], game["engine_id"])
        self.assertTrue(Path(best["model_path"]).is_file() and best["resumable"])   # resolved to a real file
        self.assertEqual(self._db("SELECT model_path FROM engines WHERE id = ?", best["id"])[0][0],
                         f"models/{best['id']}.ane.zip")
        self.assertEqual(sorted(s["kind"] for s in run["stories"]), ["play", "preview"])
        preview = next(s for s in run["stories"] if s["kind"] == "preview")
        self.assertEqual(self.client.get(f"/v1/records/stories/{preview['id']}").json()["status"], "ended")

        world = self.client.get(f"/v1/records/worlds/{run['world_id']}").json()
        self.assertEqual(world["config"]["world_definition"], config.as_dict()["world_definition"])
        upload = self.client.get(f"/v1/records/worlds/{run['world_id']}?format=yaml")
        self.assertEqual(yaml.safe_load(upload.content), world["config"])
        path = self.dir / "world.yaml"
        path.write_bytes(upload.content)
        with open(path, "rb") as stream:                                     # a recorded world can be used again
            self.assertEqual(self.client.post("/v1/config/upload", files={"file": ("world.yaml", stream)}).status_code, 200)
        self.client.post("/v1/config/reset")

    def test_every_turn_of_a_played_story_is_recorded(self):
        game = self._simulate()
        actions = []
        for _ in range(3):
            state = self.client.get(f"/v1/sessions/{game['session_id']}").json()
            if state["ended"]:
                break
            actions.append(state["actions"][0])
            self.client.post(f"/v1/sessions/{game['session_id']}/actions", json={"action": actions[-1]})
        stories = self.client.get(f"/v1/records/stories?session_id={game['session_id']}").json()["stories"]
        story = self.client.get(f"/v1/records/stories/{stories[0]['id']}").json()
        self.assertEqual(story["kind"], "play")
        self.assertEqual([t["action"] for t in story["turn_records"]], actions)
        self.assertEqual(story["turns"], len(actions))
        self.assertTrue(all(t["text"].startswith(">") or "> " in t["text"] for t in story["turn_records"]))
        self.assertIn(f"> {actions[0]}", story["transcript"])
        self.assertEqual(story["engine_id"], game["engine_id"])

    def test_recorded_engines_can_be_continued_played_exported_and_loaded(self):
        game = self._simulate()
        response = self.client.post(f"/v1/records/engines/{game['engine_id']}/continue", json={"generations": 1})
        self.assertEqual(response.status_code, 200, response.text)
        continued = response.json()
        run = self.client.get(f"/v1/records/runs/{continued['run_id']}").json()
        self.assertEqual((run["kind"], run["parent_engine_id"]), ("continue", game["engine_id"]))
        self.assertEqual([g["generation"] for g in run["generations"]], [0, 1, 2])  # continues the history
        newer = self.client.get(f"/v1/records/engines/{continued['engine_id']}").json()
        self.assertEqual(newer["parent_id"], game["engine_id"])

        champion = next(e for e in self.client.get(f"/v1/records/engines?run_id={game['run_id']}").json()["engines"]
                        if e["source"] == "generation_champion")
        self.assertEqual(self.client.post(f"/v1/records/engines/{champion['id']}/play", json={}).status_code, 200)

        model_file = self.client.get(f"/v1/records/engines/{game['engine_id']}/model")
        path = self.dir / "downloaded.ane.zip"
        path.write_bytes(model_file.content)
        self.assertEqual(EngineModel.load(path).id, game["engine_id"])
        with open(path, "rb") as stream:
            loaded = self.client.post("/v1/engines/load", files={"file": ("engine.ane.zip", stream)})
        self.assertEqual(loaded.status_code, 200, loaded.text)
        self.assertEqual(loaded.json()["engine_id"], game["engine_id"])          # the same engine, not a copy
        self.assertEqual(len(self._db("SELECT 1 FROM engines WHERE id = ?", game["engine_id"])), 1)

        exported = self.client.post("/v1/exports", json={"source": "engine", "engine_id": game["engine_id"]})
        self.assertEqual(exported.status_code, 200, exported.text)
        archive = zipfile.ZipFile(io.BytesIO(self.client.get(exported.json()["download_url"]).content))
        self.assertTrue(any(name.endswith("data/training.json") for name in archive.namelist()))
        kept = self._db("SELECT path FROM artifacts WHERE kind = 'offline_engine' AND engine_id = ?", game["engine_id"])
        self.assertTrue(kept and kept[0][0].startswith("exports/"))       # stored relative to the records folder
        self.assertTrue((records.directory() / kept[0][0]).is_file())     # a kept copy, not a temporary file

    def test_retraining_a_recorded_engine(self):
        game = self._simulate()
        response = self.client.post(f"/v1/records/engines/{game['engine_id']}/retrain",
                                    json={"candidate_count": 2, "generations": 1, "simulation_steps": 4})
        self.assertEqual(response.status_code, 200, response.text)
        run = self.client.get(f"/v1/records/runs/{response.json()['run_id']}").json()
        self.assertEqual((run["kind"], run["parent_engine_id"], run["warm_started"] >= 1), ("retrain", game["engine_id"], True))
        self.assertEqual(self.client.get("/v1/records/engines/nope").status_code, 404)


class StudioAndTerminalRecordingTests(_Records):
    def test_the_studio_records_its_runs_and_games(self):
        game = sessions.run_simulation(2, 1, 5, True)
        self.assertEqual(records.get_run(game["run_id"])["origin"], "studio")
        engines = sessions.recorded_engines()
        self.assertIn(game["engine_id"], [engine_id for _, engine_id in engines])
        outputs = app.play_recorded_ui(game["engine_id"], None, None, None)
        self.assertTrue(outputs[0] and outputs[2])                        # a session and its scene
        story_id = next(i for _, i in sessions.recorded_stories() if records.get_story(i)["session_id"] == outputs[0])
        self.assertIn("**studio play**", app.story_view_ui(story_id))
        model_path, world_path = app.download_recorded_ui(game["engine_id"])
        self.assertEqual(EngineModel.load(model_path).id, game["engine_id"])
        self.assertEqual(yaml.safe_load(Path(world_path).read_text())["world_definition"],
                         config.as_dict()["world_definition"])

    def test_the_terminal_records_its_runs_and_works_with_saved_engines(self):
        evolution, result = _train(1)
        run_id = records.start_run("terminal", settings=evolution.settings)
        run_dir = self.dir / "run"
        run_dir.mkdir()
        model = engine.record_terminal_run(evolution, result, run_id, run_dir=str(run_dir))
        self.assertTrue((run_dir / "engine_model.ane.zip").is_file())
        self.assertEqual(records.get_run(run_id)["origin"], "terminal")
        with patch.object(engine, "_runs_dir", lambda: str(self.dir / "runs")), \
                patch.object(engine, "_evaluation_worker_count", lambda size: 1):
            os.makedirs(self.dir / "runs", exist_ok=True)
            engine.engine_command(["--continue-training", str(run_dir / "engine_model.ane.zip"), "--generations", "1"])
            engine.engine_command(["--export-world", model.id, "--out", str(self.dir / "world.yaml")])
        continued = [r for r in records.list_runs() if r["kind"] == "continue"]
        self.assertEqual((continued[0]["origin"], continued[0]["parent_engine_id"]), ("terminal", model.id))
        self.assertEqual(yaml.safe_load((self.dir / "world.yaml").read_text()), model.config)


